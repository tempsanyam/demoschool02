export const generateQuickPDF = (payload: ExportDataPayload) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const margin = 14;
  let y = 20;

  doc.setFontSize(15);
  doc.text(payload.title || institutionConfig.institutionName, margin, y);
  y += 7;

  doc.setFontSize(10);
  doc.text(payload.subtitle || `${institutionConfig.institutionName} | विकास खंड: ${institutionConfig.block}, जिला: ${institutionConfig.district}`, margin, y);
  y += 6;

  if (payload.schoolName) {
    doc.text(`School: ${payload.schoolName} (UDISE: ${payload.udise || 'N/A'})`, margin, y);
    y += 6;
  }

  doc.setFontSize(9);
  doc.text(`Date: ${new Date().toLocaleDateString('en-GB')} | Generated by: ${payload.generatedBy || 'CAC Portal'} | CAC: ${institutionConfig.cac1.name} (${institutionConfig.cac1.mobile})`, margin, y);
  y += 8;

  doc.line(margin, y, 200 - margin, y);
  y += 6;

  // Simple clean table rendering in PDF
  doc.setFontSize(9);
  doc.text(`Total Records: ${payload.rows.length}`, margin, y);
  y += 8;

  const headerText = payload.headers.slice(0, 6).join('  |  ');
  doc.setFont('helvetica', 'bold');
  doc.text(headerText, margin, y);
  y += 6;
  doc.setFont('helvetica', 'normal');

  payload.rows.slice(0, 25).forEach((row) => {
    if (y > 275) {
      doc.addPage();
      y = 20;
    }
    const rowText = row.slice(0, 6).map((c) => String(c ?? '')).join('  |  ');
    doc.text(rowText.slice(0, 100), margin, y);
    y += 6;
  });

  if (payload.rows.length > 25) {
    doc.text(`... and ${payload.rows.length - 25} more records (View full dataset in Excel/Print view)`, margin, y + 4);
  }

  doc.save(`${payload.fileName || 'report'}.pdf`);
};
